import { StrictMode } from 'react'
import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import App from './App'
import { INVALID_DATA_WARNING, STORAGE_KEY, STORAGE_WARNING } from './storage'

function setup() {
  const user = userEvent.setup()
  const view = render(<StrictMode><App /></StrictMode>)
  const input = screen.getByRole('textbox', { name: 'What would you like to get done?' })
  const add = async (text: string) => {
    await user.type(input, `${text}{Enter}`)
  }
  return { user, input, add, ...view }
}

describe('todo app', () => {
  it('starts empty, rejects blank input, and adds by keyboard or button', async () => {
    const { user, input, add } = setup()
    expect(screen.getByText('A little space for what’s next.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Clear completed' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Add task' }))
    expect(input).toHaveFocus()
    expect(input).toHaveAttribute('aria-invalid', 'true')
    expect(input).toHaveAccessibleDescription('Give your task a name first.')
    await add('  Read a book  ')
    expect(screen.getByRole('checkbox', { name: 'Read a book' })).not.toBeChecked()
    expect(input).toHaveValue('')
    expect(input).toHaveFocus()
    expect(screen.getByText(/remaining$/, { selector: 'footer p' }).textContent).toBe('1 task remaining')
    await user.type(input, 'Take a walk')
    await user.click(screen.getByRole('button', { name: 'Add task' }))
    expect(screen.getByText(/remaining$/, { selector: 'footer p' }).textContent).toBe('2 tasks remaining')
    expect(input).toHaveFocus()
  })

  it('filters, completes, reactivates, and shows distinct empty states', async () => {
    const { user, input, add } = setup()
    await add('Read')
    await user.click(screen.getByRole('button', { name: /^Completed$/ }))
    expect(screen.getByText('Good things take small steps.')).toBeInTheDocument()
    expect(screen.getByText(/remaining$/, { selector: 'footer p' }).textContent).toBe('1 task remaining')
    await user.click(screen.getByRole('button', { name: /^Active$/ }))
    expect(screen.getByRole('button', { name: /^Active$/ })).toHaveAttribute('aria-pressed', 'true')
    await user.click(screen.getByRole('checkbox', { name: 'Read' }))
    expect(input).toHaveFocus()
    expect(screen.getByText('All caught up.')).toBeInTheDocument()
    expect(screen.getByText(/remaining$/, { selector: 'footer p' }).textContent).toBe('0 tasks remaining')
    await user.click(screen.getByRole('button', { name: /^Completed$/ }))
    expect(screen.getByRole('checkbox', { name: 'Read' })).toBeChecked()
    await user.click(screen.getByRole('checkbox', { name: 'Read' }))
    expect(input).toHaveFocus()
    await user.click(screen.getByRole('button', { name: /^All$/ }))
    expect(screen.getByRole('checkbox', { name: 'Read' })).not.toBeChecked()
  })

  it('edits with Enter or Save, cancels with Escape or Cancel, and never saves on blur', async () => {
    const { user, add } = setup()
    await add('Read')
    await user.click(screen.getByRole('button', { name: 'Edit Read' }))
    let editor = screen.getByRole('textbox', { name: 'Edit task' })
    expect(editor).toHaveFocus()
    await user.clear(editor)
    await user.type(editor, '  Write  {Enter}')
    expect(screen.getByRole('checkbox', { name: 'Write' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Edit Write' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Edit Write' }))
    editor = screen.getByRole('textbox', { name: 'Edit task' })
    await user.clear(editor)
    await user.type(editor, 'Discard{Escape}')
    expect(screen.getByRole('button', { name: 'Edit Write' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Edit Write' }))
    editor = screen.getByRole('textbox', { name: 'Edit task' })
    await user.clear(editor)
    await user.type(editor, 'Draft')
    await user.tab()
    expect(editor).toHaveValue('Draft')
    await user.click(screen.getByRole('button', { name: /^Cancel$/ }))
    expect(screen.getByRole('button', { name: 'Edit Write' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Edit Write' }))
    await user.clear(screen.getByRole('textbox', { name: 'Edit task' }))
    await user.click(screen.getByRole('button', { name: /^Save$/ }))
    expect(screen.getByRole('alert')).toHaveTextContent('Task text cannot be empty.')
    expect(screen.getByRole('textbox', { name: 'Edit task' })).toHaveFocus()
    await user.type(screen.getByRole('textbox', { name: 'Edit task' }), 'Plan')
    await user.click(screen.getByRole('button', { name: /^Save$/ }))
    expect(screen.getByRole('checkbox', { name: 'Plan' })).toBeInTheDocument()
  })

  it('allows only one editor and cancels drafts when switching filters', async () => {
    const { user, add } = setup()
    await add('First')
    await add('Second')
    await user.click(screen.getByRole('button', { name: 'Edit First' }))
    await user.type(screen.getByRole('textbox', { name: 'Edit task' }), 'Draft')
    await user.click(screen.getByRole('button', { name: 'Edit Second' }))
    expect(screen.getAllByRole('textbox', { name: 'Edit task' })).toHaveLength(1)
    expect(screen.getByRole('textbox', { name: 'Edit task' })).toHaveValue('Second')
    await user.click(screen.getByRole('button', { name: /^Active$/ }))
    expect(screen.queryByRole('textbox', { name: 'Edit task' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: /^Active$/ })).toHaveFocus()
    expect(screen.getByRole('checkbox', { name: 'First' })).toBeInTheDocument()
  })

  it('moves focus to a surviving row on removal, then to add when none remain', async () => {
    const { user, input, add } = setup()
    await add('First')
    await add('Second')
    await user.click(screen.getByRole('button', { name: 'Delete First' }))
    expect(screen.getByRole('checkbox', { name: 'Second' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Delete Second' }))
    expect(input).toHaveFocus()
    expect(screen.getByText('A little space for what’s next.')).toBeInTheDocument()
  })

  it('keeps focus on the next task when completion removes an active row', async () => {
    const { user, add } = setup()
    await add('First')
    await add('Second')
    await user.click(screen.getByRole('button', { name: /^Active$/ }))
    await user.click(screen.getByRole('checkbox', { name: 'First' }))
    expect(screen.getByRole('checkbox', { name: 'Second' })).toHaveFocus()
    expect(screen.getByText(/remaining$/, { selector: 'footer p' }).textContent).toBe('1 task remaining')
  })

  it('clears only completed tasks and persists edits, deletion, and clearing across remounts', async () => {
    const { user, add, unmount } = setup()
    await add('Keep')
    await add('Finish')
    await add('Delete')
    await user.click(screen.getByRole('button', { name: 'Edit Keep' }))
    await user.clear(screen.getByRole('textbox', { name: 'Edit task' }))
    await user.type(screen.getByRole('textbox', { name: 'Edit task' }), 'Updated{Enter}')
    await user.click(screen.getByRole('button', { name: 'Delete Delete' }))
    await user.click(screen.getByRole('checkbox', { name: 'Finish' }))
    await user.click(screen.getByRole('button', { name: 'Clear completed' }))
    expect(screen.getByRole('checkbox', { name: 'Updated' })).toHaveFocus()
    expect(screen.getByRole('button', { name: 'Clear completed' })).toBeDisabled()
    unmount()
    const next = setup()
    expect(screen.getAllByRole('checkbox')).toHaveLength(1)
    expect(screen.getByRole('checkbox', { name: 'Updated' })).not.toBeChecked()
    await next.user.click(screen.getByRole('checkbox', { name: 'Updated' }))
    await next.user.click(screen.getByRole('button', { name: /^Completed$/ }))
    await next.user.click(screen.getByRole('button', { name: 'Clear completed' }))
    expect(next.input).toHaveFocus()
    next.unmount()
    setup()
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  })

  it('does not write on mount, renders task text safely, and permits duplicates', async () => {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ version: 1, todos: [{ id: 'a', text: '<b>Read</b>', completed: true }] }))
    const write = vi.spyOn(Storage.prototype, 'setItem')
    const { add } = setup()
    expect(write).not.toHaveBeenCalled()
    expect(screen.getByRole('checkbox', { name: '<b>Read</b>' })).toBeChecked()
    await add('<b>Read</b>')
    expect(within(screen.getByRole('list', { name: 'Tasks' })).getAllByRole('listitem')).toHaveLength(2)
  })

  it('leaves unreadable data untouched until a valid task mutation', async () => {
    localStorage.setItem(STORAGE_KEY, 'broken')
    const { user, add } = setup()
    expect(screen.getByText(INVALID_DATA_WARNING)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /^Active$/ }))
    expect(localStorage.getItem(STORAGE_KEY)).toBe('broken')
    await add('Recover')
    expect(screen.queryByText(INVALID_DATA_WARNING)).not.toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY)!).todos[0].text).toBe('Recover')
  })

  it('continues in memory after failed writes and recovers on a later successful mutation', async () => {
    const write = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('Quota') })
    const { user, add } = setup()
    await add('In memory')
    expect(screen.getByRole('checkbox', { name: 'In memory' })).toBeInTheDocument()
    expect(screen.getByText(STORAGE_WARNING)).toBeInTheDocument()
    expect(localStorage.getItem(STORAGE_KEY)).toBeNull()
    write.mockRestore()
    await user.click(screen.getByRole('checkbox', { name: 'In memory' }))
    expect(screen.queryByText(STORAGE_WARNING)).not.toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY)!).todos[0].completed).toBe(true)
  })

  it('shows a recoverable warning when reading storage is blocked', async () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('Blocked') })
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('Blocked') })
    const { add } = setup()
    expect(screen.getByText(STORAGE_WARNING)).toBeInTheDocument()
    await add('Still usable')
    expect(screen.getByRole('checkbox', { name: 'Still usable' })).toBeInTheDocument()
    expect(screen.getByText(STORAGE_WARNING)).toBeInTheDocument()
  })
})
